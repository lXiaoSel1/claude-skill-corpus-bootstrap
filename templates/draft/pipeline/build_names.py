"""Generate chapter-names.md -- what this literature actually calls each job.

Regenerated from chapter-map.md's evidence rather than transcribed from the
chapter stubs.  The denominator is computed, never a literal -- see N_PAPERS.  Every
title here is the verbatim string the extractor pulled from the paper.
"""
import json, os, glob, collections

# Console-safety: the mimic-lit corpus is not valid UTF-8 in 140 of 165 files;
# decoding with errors="replace" manufactures U+FFFD in memory, and printing it
# on a non-UTF-8 Windows console (e.g. cp936/GBK) raises UnicodeEncodeError.  Same
# guard as every mimic-lit script (measured failure: attest.py died on almost
# every term before the guard existed).  Never remove.
import sys
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")


BASE = os.path.dirname(os.path.abspath(__file__))
# LAYOUT: the parent kept pipeline/ INSIDE references/, so "BASE/.." was
# references/.  A stamped instance puts pipeline/ at the skill root, so
# references/ is BASE/../references.  Caught 2026-08-28 when a2_build
# looked for <skill>/sample.md instead of <skill>/references/sample.md.
REF = os.path.normpath(os.path.join(BASE, "..", "references"))

# FACTORY PARAMETERIZATION: taxonomy from field-config.yaml (single
# source), written by Tier 2's approved induction.  Refuses to run
# before that -- the parent's list was economics' answer.
import _jobs
JOBS = _jobs.require_jobs()

import re

CAPS_RUN = re.compile(r'^((?:\d[\d.]*\s+)?[A-Z][A-Z0-9 ,:;&\'\-()/]{3,}?)\s+[A-Z][a-z]')


def display_title(v):
    """Clean a heading for a NAMES list. Presentation only -- the map keeps the
    raw string. Head-glued lines let P1_NUM win before P2 can fire, so the whole
    opening sentence lands in the title: shi2023multiemployer's real chapter name
    is '5. DISCUSSION AND CONCLUSION', not that plus 120 characters of body."""
    m = CAPS_RUN.match(v)
    if m and len(m.group(1)) < len(v) - 10:
        return m.group(1).rstrip()
    return v


def is_titleish(v):
    """Reject extraction debris that is not a chapter name at all."""
    body = re.sub(r'^\s*[\dIVXA-H][\d.]*\.?\s*', '', v)
    if not body or not body[0].isupper():
        return False                      # 'appendix for CDS pricing and calibration).'
    if re.search(r'\)\.\s*$|--|\bet al\b', v):
        return False
    return len(body) >= 4


cand = json.load(open(os.path.join(BASE, "a1_candidates.json"), encoding='utf-8'))
order = (sorted(glob.glob(os.path.join(BASE, "a2_out_wave*.tsv")))
         + [os.path.join(BASE, f"a2_out_{x}.tsv") for x in ("delta", "gap", "retag", "zfix")])
assign = {}
for p in [q for q in order if os.path.exists(q)]:
    for ln in open(p, encoding='utf-8'):
        f = ln.rstrip('\n').split('\t')
        if len(f) >= 3:
            try:
                assign[(f[0].strip(), int(f[1].strip().lstrip('Ll')))] = [
                    j.strip() for j in f[2].split(',') if j.strip()]
            except ValueError:
                pass

# job -> {verbatim title: [papers]}, split by heading level
top, sub = collections.defaultdict(lambda: collections.defaultdict(list)), \
           collections.defaultdict(lambda: collections.defaultdict(list))
papers_with = collections.defaultdict(set)
merged = collections.defaultdict(list)      # titles carrying >1 job
for k, r in cand.items():
    for c in r['candidates']:
        jobs = [j for j in assign.get((k, c['line']), []) if j in JOBS]
        if not jobs:
            continue
        title = display_title(c['verbatim'])
        keep = is_titleish(title)
        for j in jobs:
            papers_with[j].add(k)
            if keep:
                (top if c['level'] == 1 else sub)[j][title].append(k)
        if len(jobs) > 1 and keep:
            merged[tuple(sorted(jobs))].append((k, title))

# FACTORY PARAMETERIZATION: the denominator is the number of papers the
# chapter-map actually covers, computed here.  The parent had "60" written into
# the header AND into every job heading; a stamped instance inherited both and
# published counts against a sample size it does not have (mathematics instance: 23 papers,
# reported /60).  Nothing about the sample size may be a literal in this file.
N_PAPERS = len({k for j in JOBS for k in papers_with[j]})

L = ["# chapter-names.md — what this literature calls each job",
     "",
     "> Every title below is the **verbatim string** extracted from the paper, and every count is",
     f"> over the **{N_PAPERS}-paper sample** the chapter-map covers. Regenerated by",
     "> `pipeline/build_names.py` from `chapter-map.md`'s evidence.",
     "",
     "> **A title is not a job.** These lists are for *choosing a heading for our own manuscript*",
     "> and for recognising a chapter when reading. They must never be used to classify a paper —",
     "> that is what `chapter-map.md` is for, and it was built by reading the prose under each",
     "> heading precisely because the names do not identify the job. Where one word serves two",
     "> jobs in this field, the table of double-duty headings below is the evidence.",
     ""]

for j in JOBS:
    L += ["---", "", f"## `{j}` — {len(papers_with[j])}/{N_PAPERS} papers", ""]
    t, s = top[j], sub[j]
    if t:
        L += [f"**As a top-level chapter** ({sum(len(v) for v in t.values())} headings):", ""]
        for title, ks in sorted(t.items(), key=lambda x: (-len(x[1]), x[0].lower()))[:22]:
            tag = f" ×{len(ks)}" if len(ks) > 1 else ""
            L.append(f"- `{title}`{tag} — {', '.join(sorted(ks)[:3])}"
                     + (" …" if len(ks) > 3 else ""))
        if len(t) > 22:
            L.append(f"- … and {len(t)-22} more")
        L.append("")
    if s:
        L += [f"**As a subsection** ({sum(len(v) for v in s.values())} headings) — "
              "the job lives here in papers that fold it into a bigger chapter:", ""]
        for title, ks in sorted(s.items(), key=lambda x: (-len(x[1]), x[0].lower()))[:12]:
            tag = f" ×{len(ks)}" if len(ks) > 1 else ""
            L.append(f"- `{title}`{tag} — {', '.join(sorted(ks)[:3])}"
                     + (" …" if len(ks) > 3 else ""))
        if len(s) > 12:
            L.append(f"- … and {len(s)-12} more")
        L.append("")

L += ["---", "", "## Headings that carry two jobs at once", "",
      "One heading, two jobs — a title matched here belongs to both denominators, and the paragraphs",
      "under it must not be counted twice when a Version is induced.", "",
      "| jobs | papers | example heading |", "|---|---|---|"]
for combo, items in sorted(merged.items(), key=lambda x: -len(x[1]))[:14]:
    L.append(f"| {' + '.join(f'`{c}`' for c in combo)} | {len(items)} | "
             f"`{items[0][1][:64]}` ({items[0][0]}) |")

# FACTORY PARAMETERIZATION: the parent closed this file with two hand-written
# blocks -- three naming traps found by reading, and the headings of its own
# manuscript.  Both were economics prose (two published papers and the parent manuscript),
# and a stamped instance published them verbatim in a mathematics skill.  What
# survives is the part a script can derive; the rest is an explicit empty slot.
L += ["", "---", "", "## Traps the names alone will not show you", "",
      "A heading in the table above is a *string*, not a job. Two mechanical warnings, both",
      "derived from this corpus rather than asserted:", ""]

_dual = sorted(merged.items(), key=lambda x: -len(x[1]))
if _dual:
    L += [f"1. **{len(_dual)} title-shape(s) in this corpus carry two jobs at once** — see the table",
          "   above. A paper matched there is in both denominators, and its paragraphs must not be",
          "   counted twice when a Version is induced.", ""]
else:
    L += ["1. **No heading in this corpus was found to carry two jobs.** That is a measured zero,",
          "   not an unchecked box.", ""]

_noheading = [j for j in JOBS if not papers_with[j]]
if _noheading:
    L += [f"2. **{len(_noheading)} job(s) have zero heading evidence** — "
          + ", ".join(f"`{j}`" for j in _noheading) + ".",
          "   They are reached positionally, not by a heading rule; `slices/_manifest.md` carries the",
          "   count that was actually sliced. A zero here is a fact about headings, never about the",
          "   job's presence in the papers.", ""]
else:
    L += ["2. **Every job in the taxonomy has at least one heading in this corpus.**", ""]

L += ["> **TO-MEASURE.** Traps that only reading reveals — a word this field uses for two different",
      "> jobs, a heading whose prose contradicts its title — belong here. They cannot be derived from",
      "> the title strings, so this slot stays open until someone reads for them and writes what they",
      "> found. An empty slot is honest; inherited examples from another field are not.",
      "",
      "## What our manuscript uses", "",
      "> **TO-MEASURE.** Fill from the manuscript's own headings once",
      "> `manuscript_tex` is set in `references/field-config.yaml`. Until then this is empty by",
      "> design: an instance without a manuscript is normal, not broken.",
      ""]

p = os.path.join(REF, "chapter-names.md")
open(p, 'w', encoding='utf-8').write("\n".join(L))
print(f"wrote {p} ({os.path.getsize(p)//1024} KB)")
for j in JOBS:
    print(f"  {j:26s} {len(papers_with[j]):2d}/{N_PAPERS:<2d}  top {len(top[j]):3d} titles · sub {len(sub[j]):3d}")
