# -*- coding: utf-8 -*-
"""Tier 2 sample: pipeline/sample-keys.txt + references/sample.md.

The sample is the lit instance's STYLE-SAFE papers (corpus_meta.yaml) -- the
2026-08 template left both files to be hand-built, and a hand-built sample can
silently include a terminology-only report or an excluded scan. Waves for the
A2 agents are balanced by word count (greedy: next-longest paper into the
lightest wave), WAVE_SIZE papers per wave by default.

    py -3 pipeline/make_sample.py [--wave-size 13] [--include KEY ...] [--exclude KEY ...]

Writes:
  pipeline/sample-keys.txt   one key per line (read by a1_headings.py)
  references/sample.md       | wave | `key` | words | table (read by a2_build.py)
"""
import argparse
import os
import re
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
BASE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, BASE)
import _jobs  # noqa: E402

REF = os.path.normpath(os.path.join(BASE, "..", "references"))


def style_safe():
    meta = os.path.join(_jobs.lit_dir(), "references", "corpus_meta.yaml")
    if not os.path.exists(meta):
        sys.exit("no corpus_meta.yaml in the lit instance -- run Tier 0 first")
    out, cur, words = {}, None, 0
    for line in open(meta, encoding="utf-8"):
        m = re.match(r"\s+- id:\s*(\S+)", line)
        if m:
            cur, words = m.group(1), 0
            continue
        m = re.match(r"\s+words:\s*(\d+)", line)
        if m and cur:
            words = int(m.group(1))
        if cur and re.match(r"\s+style_safe:\s*true", line):
            out[cur] = words
            cur = None
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wave-size", type=int, default=13)
    ap.add_argument("--include", action="append", default=[])
    ap.add_argument("--exclude", action="append", default=[])
    a = ap.parse_args()
    papers = style_safe()
    for k in a.exclude:
        papers.pop(k, None)
    for k in a.include:
        papers.setdefault(k, 0)
    if not papers:
        sys.exit("no style-safe papers")
    n_waves = max(1, -(-len(papers) // a.wave_size))
    load = [0] * n_waves
    count = [0] * n_waves
    wave = {}
    for k in sorted(papers, key=lambda x: (-papers[x], x)):
        w = min((i for i in range(n_waves) if count[i] < a.wave_size),
                key=lambda i: load[i])
        wave[k] = w + 1
        load[w] += papers[k]
        count[w] += 1
    with open(os.path.join(BASE, "sample-keys.txt"), "w", encoding="utf-8",
              newline="\n") as fh:
        fh.write("\n".join(sorted(papers)) + "\n")
    L = ["# sample.md — the Tier 2 working sample and its A2 waves", "",
         "> GENERATED by `py -3 pipeline/make_sample.py` from the lit instance's",
         "> style-safe papers (corpus_meta.yaml). %d papers, %d waves,"
         " word-count balanced." % (len(papers), n_waves), "",
         "| wave | key | words |", "|---|---|---|"]
    for k in sorted(papers, key=lambda x: (wave[x], x)):
        L.append("| %d | `%s` | %d |" % (wave[k], k, papers[k]))
    L += ["", "| wave | papers | words |", "|---|---|---|"]
    for i in range(n_waves):
        L.append("| %d | %d | %d |" % (i + 1, count[i], load[i]))
    with open(os.path.join(REF, "sample.md"), "w", encoding="utf-8",
              newline="\n") as fh:
        fh.write("\n".join(L) + "\n")
    print("sample: %d papers in %d waves -> pipeline/sample-keys.txt,"
          " references/sample.md" % (len(papers), n_waves))
    for i in range(n_waves):
        print("  wave %d: %2d papers, %8d words" % (i + 1, count[i], load[i]))


if __name__ == "__main__":
    main()
